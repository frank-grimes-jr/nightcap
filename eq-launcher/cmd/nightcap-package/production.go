type productionProfile struct {
	BaseURL      string    `json:"base_url"`
	GuideURL     string    `json:"guide_url"`
	RelayURL     string    `json:"relay_url"`
	Version      string    `json:"version"`
	MinLauncher  string    `json:"minimum_launcher,omitempty"`
	KeyNotBefore time.Time `json:"key_not_before"`
	KeyNotAfter  time.Time `json:"key_not_after"`
	publish      string
}

func loadProfile(path, publish string) (*productionProfile, error) {
	if path == "" {
		if publish != "" {
			return nil, fmt.Errorf("publish requires production-profile")
		}
		return nil, nil
	}
	raw, err := readBounded(path, 8192)
	if err != nil {
		return nil, err
	}
	var p productionProfile
	d := json.NewDecoder(bytes.NewReader(raw))
	d.DisallowUnknownFields()
	if err = d.Decode(&p); err != nil {
		return nil, err
	}
	var extra any
	if d.Decode(&extra) != io.EOF {
		return nil, fmt.Errorf("trailing profile data")
	}
	p.publish = publish
	if !filepath.IsAbs(publish) {
		return nil, fmt.Errorf("absolute new publish directory required")
	}
	if err = p.validate(); err != nil {
		return nil, err
	}
	return &p, nil
}

func (p productionProfile) hosts() []string {
	u, _ := url.Parse(p.BaseURL)
	return []string{u.Hostname()}
}

func (p productionProfile) validate() error {
	u, err := url.Parse(p.BaseURL)
	if err != nil || u.Hostname() == "" {
		return fmt.Errorf("invalid production base URL")
	}
	host := u.Hostname()
	if !strings.Contains(host, ".") || strings.HasSuffix(host, ".invalid") || strings.HasSuffix(host, ".example") || strings.HasSuffix(host, ".test") || host == "example.com" || net.ParseIP(host) != nil {
		return fmt.Errorf("configure your real production hostname")
	}
	if u.Path != "" {
		return fmt.Errorf("base URL must be an HTTPS origin without trailing slash")
	}
	for _, address := range []string{p.BaseURL + "/channel.json", p.GuideURL, p.RelayURL} {
		if err := manifest.ValidateURL(address, []string{host}); err != nil {
			return err
		}
	}
	if !regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`).MatchString(p.Version) {
		return fmt.Errorf("three-part launcher version required")
	}
	if p.MinLauncher != "" && !regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`).MatchString(p.MinLauncher) {
		return fmt.Errorf("three-part minimum launcher version required")
	}
	if p.KeyNotBefore.IsZero() || !p.KeyNotAfter.After(p.KeyNotBefore) || p.KeyNotAfter.Sub(p.KeyNotBefore) > 3*366*24*time.Hour {
		return fmt.Errorf("explicit signing-key window of at most three years required")
	}
	return nil
}

func publishProduction(p *productionProfile, output string, key manifest.Key, m manifest.Manifest, raw []byte, sig manifest.Signature, data map[string][]byte) error {
	source, err := productionSource(*p, key, m)
	if err != nil {
		return err
	}
	// Never overwrite a generation or an existing compiled trust policy.
	policyPath := filepath.Join(output, "policy_production_generated.go")
	if _, err := os.Lstat(policyPath); !os.IsNotExist(err) {
		return fmt.Errorf("production policy already exists or cannot be inspected")
	}
	if err = os.Mkdir(p.publish, 0700); err != nil {
		return err
	}
	for _, f := range m.Files {
		path := filepath.Join(p.publish, "release", fmt.Sprint(m.Release), filepath.FromSlash(f.Path))
		if err = os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		if err = os.WriteFile(path, data[f.Path], 0644); err != nil {
			return err
		}
	}
	envelope, err := json.Marshal(manifest.Envelope{Manifest: raw, Signature: sig})
	if err != nil {
		return err
	}
	if err = os.WriteFile(filepath.Join(p.publish, "channel.json"), envelope, 0644); err != nil {
		return err
	}
	audit, _ := json.MarshalIndent(map[string]any{"release": m.Release, "expires": m.Expires, "key_id": key.ID, "key_expires": key.NotAfter, "channel_sha256": manifest.Digest(envelope), "files": m.Files, "scope": "Production candidate; native and hosted acceptance required"}, "", "  ")
	if err = os.WriteFile(filepath.Join(p.publish, "release-audit.json"), audit, 0644); err != nil {
		return err
	}
	f, err := os.OpenFile(policyPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return err
	}
	_, err = f.Write(source)
	return errors.Join(err, f.Sync(), f.Close())
}

func productionSource(p productionProfile, key manifest.Key, m manifest.Manifest) ([]byte, error) {
	var inventory strings.Builder
	for _, f := range m.Files {
		fmt.Fprintf(&inventory, "%q:true,", f.Path)
	}
	source := fmt.Sprintf(`//go:build production
// Code generated by nightcap-package. DO NOT EDIT.
package launcher
import ("time"; "encoding/hex"; "nightcap/eq-launcher/internal/manifest")
func DefaultPolicy() Policy {
 public, err := hex.DecodeString(%q); if err != nil { panic(err) }
 return Policy{Label:"Nightcap", EnablePlay:true, AutomaticUpdates:true, EnvelopeURL:%q, GuideURL:%q, RelayURL:%q, Trust:manifest.Trust{
 ReleaseInventory:true, LauncherVersion:%q, Hosts:[]string{%q},
 Keys:[]manifest.Key{{ID:%q,Public:public,NotBefore:time.Unix(%d,0),NotAfter:time.Unix(%d,0)}},
 Inventory:map[string]bool{%s}, Retired:map[string]bool{"nektulos.eqg":true,"lavastorm.eqg":true}, RetiredSHA256:map[string]string{"nektulos.eqg":%q,"lavastorm.eqg":%q},
 }}
}
`, hex.EncodeToString(key.Public), p.BaseURL+"/channel.json", p.GuideURL, p.RelayURL, p.Version, p.hosts()[0], key.ID, key.NotBefore.Unix(), key.NotAfter.Unix(), inventory.String(), classicNektulosRetirementSHA256, classicLavastormRetirementSHA256)
	return format.Source([]byte(source))
}
