"""Generate the 16 raid definitions and their native loot mapping from one catalog."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/items/classic-raid-augments"
CATALOG = ROOT / "config/classic-raid-augments.json"
HEADER = ROOT / "server-mods/code/common/raid_augment_sources.h"


def literal(value):
    if isinstance(value, str):
        return "X'" + value.encode("utf-8").hex() + "'"
    return str(int(value))


def generate():
    items = json.loads(CATALOG.read_text())
    assert [x["id"] for x in items] == list(range(963200, 963216))
    common = dict(itemclass=0, itemtype=54, slots=1 << 17, classes=65535,
                  races=65535, reqlevel=50, reclevel=50, augtype=1 << 21,
                  augrestrict=1, loregroup=-1, nopet=1, norent=1, nodrop=1,
                  magic=1, size=1, weight=0, price=0, sellrate=0, stackable=0,
                  maxcharges=0, icon=0, idfile="IT63")
    stats = sorted({k for i in items for k in i["stats"]})
    rows, sources = [], []
    for i in items:
        row = dict(id=i["id"], Name=i["name"], lore=i["lore"], **common)
        row["icon"] = i["icon"]
        row.update({key: i["stats"].get(key, 0) for key in stats})
        rows.append(row)
        for zone, npc, chance in i["sources"]:
            sources.append((zone, npc, i["id"], chance))
    assert len(set((z, n) for z, n, _, _ in sources)) == len(sources)
    cols = ",".join(f"`{k}`" for k in rows[0])
    values = ",\n".join("(" + ",".join(map(literal, r.values())) + ")" for r in rows)
    # Acquire the unique ID range before checking for collisions; replays verify
    # all fields except administrative timestamps. Existing definitions are never updated.
    sql = f"""-- Run on a stopped test stack with the paired loader and zone.
DELIMITER //
CREATE OR REPLACE PROCEDURE nightcap_install_raid_augments()
BEGIN
  DECLARE existing_count INT;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    ROLLBACK;
    DROP TEMPORARY TABLE IF EXISTS raid_aug_expected;
    RESIGNAL;
  END;
  CREATE TEMPORARY TABLE raid_aug_expected LIKE items;
  INSERT INTO raid_aug_expected ({cols}) VALUES
{values};
  SELECT GROUP_CONCAT(CONCAT('BINARY i.`',COLUMN_NAME,'` <=> BINARY e.`',COLUMN_NAME,'`')
         ORDER BY ORDINAL_POSITION SEPARATOR ' AND ') INTO @raid_aug_compare
    FROM information_schema.columns WHERE table_schema=DATABASE() AND table_name='items'
      AND COLUMN_NAME NOT IN ('created','updated','verified');
  IF @@group_concat_max_len < 65536 OR @raid_aug_compare IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Full raid item comparison requires group_concat_max_len >= 65536';
  END IF;
  START TRANSACTION;
  SELECT COUNT(*) INTO existing_count FROM items WHERE id BETWEEN 963200 AND 963215 FOR UPDATE;
  IF existing_count = 0 THEN
    INSERT INTO items ({cols}) SELECT {cols} FROM raid_aug_expected;
  END IF;
  SET @raid_aug_sql=CONCAT('SELECT COUNT(*) INTO @raid_aug_matches FROM items i JOIN raid_aug_expected e ON i.id=e.id WHERE ',@raid_aug_compare);
  PREPARE raid_aug_stmt FROM @raid_aug_sql;
  EXECUTE raid_aug_stmt;
  DEALLOCATE PREPARE raid_aug_stmt;
  IF @raid_aug_matches <> 16 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Raid augment identity or content collision';
  END IF;
  COMMIT;
  DROP TEMPORARY TABLE raid_aug_expected;
END//
DELIMITER ;
SET @raid_aug_previous_len=@@SESSION.group_concat_max_len;
SET SESSION group_concat_max_len=GREATEST(65536,@@SESSION.group_concat_max_len);
CALL nightcap_install_raid_augments();
SET SESSION group_concat_max_len=@raid_aug_previous_len;
DROP PROCEDURE nightcap_install_raid_augments;
"""
    header = """// Generated by tools/classic_raid_augments.py.
#pragma once
#include "common/raid_augment.h"

namespace NightcapRaidAug {
struct Drop { unsigned zone, npc, item, percent; };
constexpr Drop Sources[] = {
""" + "".join(f"\t{{{z}, {n}, {i}, {p}}},\n" for z, n, i, p in sources) + """};
inline const Drop *FindDrop(unsigned zone, unsigned npc)
{
	if (zone == 186) { zone = 76; } // Managed Hate B uses the classic NPC IDs.
	for (const auto &drop : Sources) {
		if (drop.zone == zone && drop.npc == npc) { return &drop; }
	}
	return nullptr;
}
}
"""
    return {OUT / "content.sql": sql, HEADER: header}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generate().items():
        if args.check:
            if path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"Generated artifact differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
