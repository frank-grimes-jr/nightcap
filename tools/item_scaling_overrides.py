"""Reproducible numeric overrides for fresh tier generation, never live migration.

Existing servers use thj_combined_content.py's captured, full-row transitions.
This final bootstrap block preserves explicit starter and researched item policy.
"""
import argparse,json,re
from pathlib import Path
import starter_retune,thj_item_parity
from dungeon_catalog import legacy_items
from rabid_bear import sql_value

ROOT=Path(__file__).resolve().parents[1]
START='-- BEGIN GENERATED REVIEWED ITEM SCALING'
END='-- END GENERATED REVIEWED ITEM SCALING'

def protected_bases():
    from thj_stock_scaling import stock
    return set(stock()) | starter_retune.APPROVED_IDS | {r['base_id'] for r in thj_item_parity.catalog()['items']}

def overrides():
    reference=json.loads((ROOT/'docs/items/starter-retune-reference.json').read_text(encoding='utf-8'))
    starters,_=starter_retune.propose(reference,legacy_items())
    fields={'ac','damage','spelldmg','healamt',*starter_retune.POOLS,*starter_retune.PRIMARY,
            *starter_retune.RESISTS,*starter_retune.UTILITY}
    result=[]
    for row in starters.values():
        owned=fields | {f for f in row if f.startswith('heroic_')}
        result.append(dict(id=row['id'],name=row['Name'],fields={k:row[k] for k in sorted(owned)},clamp=False))
    before=thj_item_parity.snapshot()
    for target in thj_item_parity.catalog()['items']:
        result.append(dict(id=target['id'],name=before[target['id']]['Name'],fields=target['fields'],clamp=False))
        if target['id']-target['base_id']!=600000:continue
        capped={f:v for f,v in target['fields'].items() if f not in ('delay','range') and v>=0}
        for offset in (200000,400000):
            ident=target['base_id']+offset
            if ident in before:
                result.append(dict(id=ident,name=before[ident]['Name'],fields=capped,clamp=True))
    assert len({r['id'] for r in result})==len(result)
    return sorted(result,key=lambda r:r['id'])

def block():
    rows=overrides()
    normal=thj_item_parity.snapshot()
    lines=[START,'-- Generated by tools/item_scaling_overrides.py. Fresh bootstrap only.',
           'DELIMITER //','CREATE PROCEDURE nightcap_reviewed_item_scaling()', 'BEGIN']
    for row in rows:
        ident=row['id'];name=sql_value(row['name'])
        lines.append(f" IF (SELECT COUNT(*) FROM items WHERE id={ident})<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Missing reviewed item'; END IF;")
        lines.append(f" IF EXISTS(SELECT 1 FROM items WHERE id={ident} AND BINARY Name<>BINARY {name}) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Reviewed item identity drift'; END IF;")
    # Never turn a researched top tier below its present Normal source.
    for row in thj_item_parity.catalog()['items']:
        lines.append(f" IF (SELECT COUNT(*) FROM items WHERE id={row['base_id']})<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Missing reviewed Normal item'; END IF;")
        name=sql_value(normal[row['base_id']]['Name'])
        lines.append(f" IF EXISTS(SELECT 1 FROM items WHERE id={row['base_id']} AND BINARY Name<>BINARY {name}) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Reviewed Normal identity drift'; END IF;")
        below=' OR '.join(f'`{f}`>{v}' for f,v in row['fields'].items() if f not in ('delay','range'))
        lines.append(f" IF EXISTS(SELECT 1 FROM items WHERE id={row['base_id']} AND ({below})) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Reviewed tier below Normal'; END IF;")
    for row in rows:
        assignments=','.join(f'`{f}`='+ (f'LEAST(`{f}`,{v})' if row['clamp'] else str(v)) for f,v in sorted(row['fields'].items()))
        lines.append(f" UPDATE items SET {assignments} WHERE id={row['id']};")
    lines+=['END//','DELIMITER ;','CALL nightcap_reviewed_item_scaling();','DROP PROCEDURE nightcap_reviewed_item_scaling;',END]
    return '\n'.join(lines)

def sync(check=False):
    path=ROOT/'eq-solo-gm/scripts/tiered_loot_setup.sql'
    text=path.read_text(encoding='utf-8');generated=block()
    if START in text:
        text,count=re.subn(re.escape(START)+'.*?'+re.escape(END),lambda _:generated,text,flags=re.S)
        assert count==1
    else:text=text.rstrip()+'\n\n'+generated+'\n'
    if check:
        if path.read_text(encoding='utf-8')!=text:raise ValueError('Reviewed item override SQL drift')
    else:path.write_text(text,encoding='utf-8')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true')
    sync(parser.parse_args().check)
