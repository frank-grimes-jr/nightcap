"""Generate immutable pet class attribution from the preserved original spell file."""
import argparse
import hashlib
from pathlib import Path

SOURCE_SHA256 = "bae7ba7d897962f67581e3e731b94f4a31898d160c30c2edb74912b21aa11880"
PET_EFFECTS = {33, 71, 106, 108}
ROOT = Path(__file__).resolve().parents[1]


def parse(raw):
    result, seen = [], set()
    for line in raw.decode("latin1").splitlines():
        fields = line.split("^")
        if len(fields) < 120:
            raise ValueError("Missing spell policy fields")
        spell = int(fields[0])
        if spell < 0 or spell in seen:
            raise ValueError("Invalid/duplicate spell id")
        seen.add(spell)
        if not PET_EFFECTS.intersection(map(int, fields[86:98])):
            continue
        levels = list(map(int, fields[104:120]))
        if any(n < 0 or n > 255 for n in levels):
            raise ValueError("Invalid original class level")
        result.append((spell, levels))
    return sorted(result)


def generate(raw):
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Original spell catalog hash changed; review before generating")
    rows = parse(raw)
    if len(rows) != 547:
        raise ValueError("Unexpected pet catalog coverage")
    lines = ["// Generated by tools/generate_pet_spell_catalog.py; do not edit.",
             "// Original spell file SHA256: " + SOURCE_SHA256,
             "#pragma once", "#include <array>", "#include <cstdint>",
             "namespace NightcapPetClasses {", "struct Spell { uint32_t id; std::array<uint8_t, 16> levels; };",
             "inline constexpr Spell Catalog[] = {"]
    lines += ["\t{" + str(spell) + ", {{" + ",".join(map(str,levels)) + "}}}," for spell, levels in rows]
    lines += ["};", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "server-mods/code/common/pet_spell_catalog.h"
    generated = generate(args.source.read_bytes())
    if args.check:
        if output.read_text(encoding="utf-8") != generated:
            raise ValueError("Generated pet class catalog is stale")
    else:
        output.write_text(generated, encoding="utf-8", newline="\n")
    print("PASS: 547 original pet spell ownership records")


if __name__ == "__main__":
    main()
