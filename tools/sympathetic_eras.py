"""Build and verify the server's per-expansion sympathetic rank ceiling."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'config/sympathetic-eras.json'
HEADER = ROOT / 'server-mods/code/zone/nightcap_sympathetic_eras.h'


def release_caps(rows):
    caps = []
    names = set()
    levels = {'strike': 0, 'healing': 0}
    for index, row in enumerate(rows):
        if set(row) - {'id', 'name', *levels} or type(row.get('id')) is not int or row['id'] != index:
            raise ValueError(f'Expected ordered expansion {index}')
        name = row.get('name')
        if not isinstance(name, str) or not name.strip() or name in names:
            raise ValueError(f'Invalid expansion name at {index}')
        names.add(name)
        for line in levels:
            if line in row:
                rank = row[line]
                if type(rank) is not int or rank != levels[line] + 1:
                    raise ValueError(f'{name} must introduce the next {line} rank')
                levels[line] = rank
        caps.append((name, levels['strike'], levels['healing']))
    if not caps or caps[0][0] != 'Classic':
        raise ValueError('Classic must be expansion zero')
    return caps


def header(caps):
    return '\n'.join([
        '// Generated by tools/sympathetic_eras.py from config/sympathetic-eras.json.',
        '#pragma once', '', 'namespace NightcapSympathetic {',
        'enum class Line { Strike, Healing };',
        'struct Caps { int strike; int healing; };',
        'constexpr Caps EraCaps[] = {',
        *(f'\t{{{strike}, {healing}}}, // {name}' for name, strike, healing in caps),
        '};',
        'constexpr int EraCount = sizeof(EraCaps) / sizeof(EraCaps[0]);', '',
        'constexpr bool RankEnabled(int expansion, Line line, int rank)',
        '{',
        '\tif (expansion < 0 || expansion >= EraCount || rank < 1) {',
        '\t\treturn false;', '\t}',
        '\treturn line == Line::Strike ? rank <= EraCaps[expansion].strike :',
        '\t\tline == Line::Healing && rank <= EraCaps[expansion].healing;',
        '}', '} // namespace NightcapSympathetic', '',
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--era', type=int)
    args = parser.parse_args()
    caps = release_caps(json.loads(CATALOG.read_bytes())['expansions'])
    content = header(caps)
    if args.check:
        if HEADER.read_text(encoding='utf8') != content:
            parser.exit(1, 'Sympathetic rank policy header differs from catalog.\n')
    else:
        HEADER.write_text(content, encoding='utf8', newline='\n')
    if args.era is not None:
        if 0 <= args.era < len(caps):
            name, strike, healing = caps[args.era]
            print(f'{name} ({args.era}) permits Strike through {strike} and Healing through {healing}.')
        else:
            print(f'No sympathetic clicks enabled for expansion {args.era}.')


if __name__ == '__main__':
    main()
