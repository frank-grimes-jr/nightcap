"""Generate the native AA allowlist. Offline only; never writes to PEQ."""
import argparse
import collections
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def compile_policy(tables, config):
    abilities = {a['id']: a for a in tables['aa_ability']}
    ranks = {r['id']: r for r in tables['aa_ranks']}
    prereqs = collections.defaultdict(dict)
    for p in tables.get('aa_rank_prereqs', []):
        if p['aa_id'] > 0 and p['points'] > 0:
            prereqs[p['rank_id']][p['aa_id']] = max(p['points'], prereqs[p['rank_id']].get(p['aa_id'], 0))
    candidates, owners = {}, {}
    for aid, ability in sorted(abilities.items()):
        if not ability.get('enabled'):
            continue
        levels = config['rank_levels'].get(str(aid), config['core_rank_levels']
            if aid in config['core_abilities'] else config['default_rank_levels'])
        permitted = (aid > 0 and ability.get('category') not in (3, 4)
                     and aid not in config['deferred_abilities'] and not ability.get('charges', 0)
                     and (not ability.get('grant_only') or aid in config['grant_only_exceptions']))
        rid, ordinal, seen, inherited = ability['first_rank_id'], 0, set(), {}
        while rid in ranks:
            if rid in seen:
                raise ValueError(f'rank chain cycle: ability {aid}, rank {rid}')
            if rid in owners:
                raise ValueError(f'shared rank {rid}: {owners[rid]} and {aid}')
            owners[rid] = aid
            seen.add(rid)
            rank = ranks[rid]
            ordinal += 1
            for dep, count in prereqs[rid].items():
                inherited[dep] = max(inherited.get(dep, 0), count)
            permitted = permitted and ordinal <= len(levels) and (
                rank['expansion'] <= config['expansion_max'] or aid in config['later_exceptions'])
            if permitted:
                candidates[aid, ordinal] = {'rank_id': rid, 'ability_id': aid, 'ordinal': ordinal,
                    'level': max(levels[ordinal - 1], rank['level_req']), 'expansion': rank['expansion'],
                    'classes': ability['classes'], 'name': ability.get('name', str(aid)),
                    'prereqs': dict(inherited)}
            rid = rank['next_id']
    resolved, visiting = {}, set()

    def resolve(key):
        if key in resolved:
            return resolved[key]
        if key not in candidates or key in visiting:
            return None
        visiting.add(key)
        row = candidates[key]
        dependencies = list(row['prereqs'].items())
        if row['ordinal'] > 1:
            dependencies.append((row['ability_id'], row['ordinal'] - 1))
        level = row['level']
        for dep in dependencies:
            required = resolve(dep)
            if required is None:
                level = None
                break
            level = max(level, required)
        visiting.remove(key)
        resolved[key] = level
        return level

    result = []
    for key, row in sorted(candidates.items()):
        level = resolve(key)
        if level is not None and level <= 50:
            result.append({**row, 'level': level})
    return sorted(result, key=lambda r: r['rank_id'])


def header(rows, config, catalog):
    lines = ['// Generated by tools/aa_tbs_policy.py; edit config/aa-policy.json, then regenerate.',
             '// Policy SHA256: ' + digest(config), '// Catalog SHA256: ' + digest(catalog),
             '#pragma once', '#include <algorithm>', '#include <iterator>',
             'namespace NightcapAA {',
             'struct RankPolicy { int rank_id; int ability_id; int ordinal; int expansion; int level; };',
             'inline constexpr RankPolicy Ranks[] = {']
    for r in rows:
        lines.append('\t{' + ', '.join(str(r[k]) for k in ('rank_id', 'ability_id', 'ordinal', 'expansion', 'level')) + '},')
    lines += ['};',
              'inline int RequiredLevel(int rank_id, int ability_id, int ordinal, int expansion) {',
              '\tconst auto it = std::lower_bound(std::begin(Ranks), std::end(Ranks), rank_id,',
              '\t\t[](const RankPolicy& row, int id) { return row.rank_id < id; });',
              '\treturn it != std::end(Ranks) && it->rank_id == rank_id && it->ability_id == ability_id &&',
              '\t\tit->ordinal == ordinal && it->expansion == expansion ? it->level : 0;',
              '}', '} // namespace NightcapAA', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    config = json.loads((ROOT / 'config/aa-policy.json').read_text())
    catalog = json.loads(gzip.decompress((ROOT / config['catalog']).read_bytes()))
    rows = compile_policy(catalog, config)
    target = ROOT / 'server-mods/code/common/nightcap_aa_policy.h'
    generated = header(rows, config, catalog)
    if args.check:
        assert target.read_text() == generated, 'Generated AA policy is stale'
    else:
        target.write_text(generated, encoding='utf-8', newline='\n')
    print(json.dumps({'ranks': len(rows), 'families': len({r['ability_id'] for r in rows}),
                      'policy_sha256': digest(config), 'catalog_sha256': digest(catalog)}))


if __name__ == '__main__':
    main()
