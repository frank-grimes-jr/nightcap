            database.exists = scenario == "native-existing";
            client.SetMulticlassSlot(2, 2);
            check(client.inventory.Classes() == "WAR/CLR/---", "native second class inventory label stale");
            client.SetMulticlassSlot(3, 11);
            check(client.inventory.Classes() == "WAR/CLR/NEC", "native third class inventory label stale");
            check(client.m_nightcap_ui_generation == initial_generation + 2, "native adoption duplicated or omitted snapshots");
            check(client.aa_rows == 3, "native adoption duplicated or omitted AA table refreshes");
            client.SetMulticlassSlot(3, 11);
            check(client.aa_rows == 3, "unchanged native slot resent AA table");
