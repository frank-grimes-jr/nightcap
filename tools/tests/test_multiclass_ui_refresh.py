class MulticlassUIRefresh(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temporary = tempfile.TemporaryDirectory(prefix="nightcap-ui-refresh-")
        cls.addClassCleanup(cls.temporary.cleanup)
        output = Path(cls.temporary.name)
        methods = "\n".join((
            function((ZONE / "client.cpp").read_text(), "uint32 Client::ReconcileMulticlassSkills("),
            function((ZONE / "aa.cpp").read_text(), "void Client::SendLoadedAlternateAdvancementTable("),
            function((ZONE / "aa.cpp").read_text(), "void Client::SendAlternateAdvancementTable("),
            function((ZONE / "aa.cpp").read_text(), "void Client::RefreshNightcapUI("),
            function((ZONE / "aa.cpp").read_text(), "void Client::SetMulticlassSlot("),
        ))
        (output / "test.cpp").write_text(FIXTURE + methods + CONTROLS)
        include = ROOT / "eq-client-dll/src"
        (output / "build.cmd").write_text(
            '@echo off\n'
            'call "C:/BuildTools/VC/Auxiliary/Build/vcvars32.bat" >nul || exit /b 1\n'
            f'cl /nologo /EHsc /W4 /std:c++17 /I"{include}" test.cpp /Fe:test.exe >build.log 2>&1\n'
            'exit /b %errorlevel%\n'
        )
        build = subprocess.run(["cmd", "/d", "/c", str(output / "build.cmd")], cwd=output)
        if build.returncode:
            raise AssertionError((output / "build.log").read_text())
        cls.executable = output / "test.exe"

    def run_scenario(self, scenario):
        result = subprocess.run([self.executable, scenario], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_second_class_updates_inventory_without_zoning(self):
        self.run_scenario("second")

    def test_third_class_updates_inventory_without_zoning(self):
        self.run_scenario("third")

    def test_consecutive_selections_advance_same_session_snapshot(self):
        self.run_scenario("consecutive")

    def test_noop_and_level_only_reconciliation_do_not_resend(self):
        self.run_scenario("unchanged")

    def test_metadata_waits_for_optin_but_ordinary_aa_rows_refresh(self):
        self.run_scenario("no-opt-in")

    def test_native_existing_character_selection_refreshes_once(self):
        self.run_scenario("native-existing")

    def test_native_new_character_selection_refreshes_once(self):
        self.run_scenario("native-insert")


if __name__ == "__main__":
    unittest.main()
