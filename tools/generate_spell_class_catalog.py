"""Pin spell eligibility independently of legacy globally widened database rows."""
import argparse
import hashlib
from pathlib import Path
from generate_pet_spell_catalog import SOURCE_SHA256

ROOT = Path(__file__).resolve().parents[1]


def parse(raw):
    rows, seen = [], set()
    for line in raw.decode('latin1').splitlines():
        fields = line.split('^')
        # Historical custom AA row has another schema and an out-of-range ID.
        # It is not a learnable spell (current recall uses its separate AA path).
        if len(fields) == 230 and fields[:2] == ['99001', 'Ancient Attunement']:
            continue
        if len(fields) != 237:
            raise ValueError('Expected 237 RoF2 spell fields')
        spell = int(fields[0])
        levels = tuple(map(int, fields[104:120]))
        if spell < 0 or spell in seen or any(n < 0 or n > 255 for n in levels):
            raise ValueError('Invalid or duplicate spell eligibility')
        seen.add(spell)
        if any(0 < n < 255 for n in levels):
            rows.append((spell, tuple(n if n else 255 for n in levels)))
    if not seen:
        raise ValueError('Empty spell catalog')
    return sorted(rows)


def generate(raw):
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError('Original spell catalog hash changed; review before generating')
    rows = parse(raw)
    lines = ['// Generated by tools/generate_spell_class_catalog.py; do not edit.',
             '// Original spell file SHA256: '+SOURCE_SHA256,
             '#pragma once', '#include <cstdint>', '#include <cstddef>',
             'namespace NightcapSpellClasses {',
             'struct Spell { uint32_t id; uint8_t levels[16]; };',
             'inline constexpr Spell Catalog[] = {']
    lines += ['\t{'+str(spell)+', {'+','.join(map(str,levels))+'}},' for spell,levels in rows]
    lines += ['};', '''
inline const Spell* Find(uint32_t id)
{
\tsize_t first = 0, last = sizeof(Catalog) / sizeof(Catalog[0]);
\twhile (first < last) {
\t\tconst size_t middle = first + (last - first) / 2;
\t\tif (Catalog[middle].id < id) { first = middle + 1; }
\t\telse { last = middle; }
\t}
\treturn first < sizeof(Catalog) / sizeof(Catalog[0]) && Catalog[first].id == id ? &Catalog[first] : nullptr;
}
inline uint8_t Level(uint32_t spell_id, uint32_t class_id)
{
\tconst auto spell = Find(spell_id);
\treturn spell && class_id >= 1 && class_id <= 16 ? spell->levels[class_id - 1] : 255;
}
inline uint32_t Mask(uint32_t spell_id)
{
\tconst auto spell = Find(spell_id);
\tuint32_t mask = 0;
\tif (spell) {
\t\tfor (unsigned i = 0; i < 16; ++i) {
\t\t\tif (spell->levels[i] > 0 && spell->levels[i] < 255) { mask |= uint32_t(1) << i; }
\t\t}
\t}
\treturn mask;
}
}''', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT/'server-mods/code/common/spell_class_catalog.h'
    generated = generate(args.source.read_bytes())
    if args.check:
        if output.read_text() != generated:
            raise ValueError('Spell class catalog is stale')
    else:
        output.write_text(generated, newline='\n')
    print('PASS: canonical spell eligibility catalog')
