"""Pinned stock EQ equipment model, exact THJ observations, guarded offline plans."""
from copy import deepcopy
from functools import lru_cache
import argparse,gzip,hashlib,json
from pathlib import Path
import starter_retune,thj_item_parity
from thj_item_migration import migration

ROOT=Path(__file__).resolve().parents[1]
RELEASE=ROOT/'docs/releases/thj-behaviors-20261019'
FIELDS=thj_item_parity.FIELDS
EPICS={5532,10099,10650,10651,10652,10908,11057,11566,14341,14383,20487,20488,20490,20542,20544,36223,36224,66175}
DOUBLE=set('ac hp mana astr asta aagi adex aint awis acha mr fr cr dr pr damage regen manaregen'.split())
HEROICS=dict(zip('heroic_str heroic_sta heroic_agi heroic_dex heroic_int heroic_wis heroic_cha heroic_fr heroic_cr heroic_mr heroic_dr heroic_pr'.split(),'astr asta aagi adex aint awis acha fr cr mr dr pr'.split()))
SIGNED8=set('astr asta aagi adex aint awis acha mr fr cr dr pr combateffects shielding stunresist strikethrough spellshield avoidance accuracy'.split())
UNSIGNED8={'delay','range','elemdmgamt'}
UNSIGNED32={'damage','backstabdmg'}

def bounds(field):
    return (-128,127) if field in SIGNED8 else (0,255) if field in UNSIGNED8 else (0,4294967295) if field in UNSIGNED32 else (-2147483648,2147483647)

TIERS=((200000,'Polished',1),(400000,'Exalted',2),(600000,'Ascended',3))

def rounded(numerator,denominator):
    if numerator<0:raise ValueError('Rounding requires a nonnegative numerator')
    return (2*numerator+denominator)//(2*denominator)

@lru_cache(maxsize=1)
def stock():
    rows=json.loads(gzip.decompress((ROOT/'tools/fixtures/thj-stock-equipment.json.gz').read_bytes()))
    return {int(row['id']):row for row in rows}

@lru_cache(maxsize=1)
def observed():
    return {row['base_id']:row for row in thj_item_parity.catalog()['items'] if row['id']-row['base_id']==600000}

def top_target(base):
    target={f:int(base[f]) for f in FIELDS}
    for f in DOUBLE:
        if target[f]>0:target[f]*=2
    if target['haste']>0:target['haste']=rounded(target['haste']*3,2)
    if not target['spelldmg']:target['spelldmg']=max(2*max(int(base['aint']),0),max(int(base['awis']),0))
    if not target['healamt']:target['healamt']=2*max(int(base['awis']),0)
    if not target['accuracy']:target['accuracy']=(max(int(base['adex']),0)+1)//2
    # Exact ordinary observations win; unknown fields retain the model/stock.
    exact=observed().get(int(base['id']),{}).get('fields',{})
    target.update({f:v for f,v in exact.items() if f not in HEROICS})
    for heroic,primary in HEROICS.items():
        if not int(base[heroic]):target[heroic]=rounded(max(target[primary],0),4)
    target.update(exact)
    for f,v in target.items():
        low,high=bounds(f)
        if not low<=v<=high:raise ValueError(f'Native item field overflow: {base["id"]}/{f}={v}')
    return target

def tier_target(base,tier):
    if tier not in (1,2,3):raise ValueError('Unknown quality')
    top=top_target(base);target={}
    for field,value in top.items():
        normal=int(base[field])
        if tier==3:target[field]=value
        elif field in HEROICS:target[field]=normal
        elif value>=normal:target[field]=normal+rounded((value-normal)*tier,3)
        else:raise ValueError(f'Tier below stock: {base["id"]}/{field}')
    return target

def plan(current):
    pairs=[];excluded=[];included=[]
    for ident,base in sorted(stock().items()):
        if ident in starter_retune.APPROVED_IDS or ident in EPICS:continue
        family=[current.get(ident+offset) for offset,_,_ in TIERS]
        normal=current.get(ident)
        if normal is None or normal['Name']!=base['Name'] or any(row is None or row['Name']!=base['Name']+' ('+label+')' for row,(_,label,_) in zip(family,TIERS)):
            excluded.append(dict(id=ident,reason='missing or nonstandard family identity'));continue
        # Never silently rebaseline a custom Normal definition.
        drift=[f for f in FIELDS if int(normal[f])!=int(base[f])]
        if drift:
            excluded.append(dict(id=ident,reason='Normal numeric drift',fields=drift));continue
        try:targets={tier:tier_target(base,tier) for _,_,tier in TIERS}
        except ValueError as error:
            excluded.append(dict(id=ident,reason=str(error)));continue
        included.append(ident)
        for row,(_,_,tier) in zip(family,TIERS):
            after=dict(row);after.update(targets[tier])
            if any(str(after[f])!=str(row[f]) for f in FIELDS):pairs.append((row,after))
    return pairs,dict(included_families=included,excluded_families=excluded)

def bootstrap_sql():
    from rabid_bear import sql_value
    fields=sorted(FIELDS)
    lines=['-- Generated by tools/thj_stock_scaling.py. Fresh bootstrap only.',
           'DROP TEMPORARY TABLE IF EXISTS nightcap_stock_targets;',
           'CREATE TEMPORARY TABLE nightcap_stock_targets (id INT PRIMARY KEY, base_id INT, expected_name VARCHAR(255), normal_hash CHAR(64), '+','.join('`'+f+'` BIGINT' for f in fields)+') ENGINE=InnoDB;']
    batch=[]
    for ident,base in sorted(stock().items()):
        if ident in EPICS:continue
        try:targets={tier:tier_target(base,tier) for _,_,tier in TIERS}
        except ValueError:continue
        for offset,label,tier in TIERS:
            batch.append('('+','.join([str(ident+offset),str(ident),sql_value(base['Name']+' ('+label+')'),sql_value(hashlib.sha256('|'.join(str(base[f]) for f in fields).encode()).hexdigest())]+[str(targets[tier][f]) for f in fields])+')')
            if len(batch)==1000:
                lines.append('INSERT INTO nightcap_stock_targets VALUES '+','.join(batch)+';');batch=[]
    if batch:lines.append('INSERT INTO nightcap_stock_targets VALUES '+','.join(batch)+';')
    # Fresh bootstrap starts from the pinned stock PEQ schema. Normal is untouched.
    normal_guard="SHA2(CONCAT_WS('|',"+','.join('n.`'+f+'`' for f in fields)+"),256)=p.normal_hash"
    family_guard=" JOIN items pol ON pol.id=n.id+200000 AND BINARY pol.Name=BINARY CONCAT(n.Name,' (Polished)') JOIN items exa ON exa.id=n.id+400000 AND BINARY exa.Name=BINARY CONCAT(n.Name,' (Exalted)') JOIN items ascended ON ascended.id=n.id+600000 AND BINARY ascended.Name=BINARY CONCAT(n.Name,' (Ascended)') "
    lines.append('UPDATE items t JOIN nightcap_stock_targets p ON p.id=t.id JOIN items n ON n.id=p.base_id '+family_guard+' SET '+','.join('t.`'+f+'`=p.`'+f+'`' for f in fields)+" WHERE BINARY t.Name=BINARY p.expected_name AND BINARY p.expected_name=BINARY CONCAT(n.Name,CASE t.id-p.base_id WHEN 200000 THEN ' (Polished)' WHEN 400000 THEN ' (Exalted)' ELSE ' (Ascended)' END) AND "+normal_guard+';')
    lines.append('DROP TEMPORARY TABLE nightcap_stock_targets;')
    return '\n'.join(lines)+'\n'

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--capture',type=Path);parser.add_argument('--bootstrap',type=Path);args=parser.parse_args()
    if args.bootstrap:
        args.bootstrap.write_text(bootstrap_sql(),encoding='utf-8');return
    if not args.capture:parser.error('--capture or --bootstrap is required')
    data=json.loads(gzip.decompress(args.capture.read_bytes()));current={int(row['id']):row for row in data['rows']}
    pairs,audit=plan(current)
    for name,ps in [('gear-forward.sql.gz',pairs),('gear-rollback.sql.gz',[(new,old) for old,new in pairs])]:
        sql=migration(ps,data['columns']).replace('nightcap_thj_items_20261018','nightcap_thj_stock_20261019')
        (RELEASE/name).write_bytes(gzip.compress(sql.encode(),compresslevel=6,mtime=0))
    audit.update(changed_definitions=len(pairs),capture_sha256=hashlib.sha256(args.capture.read_bytes()).hexdigest(),normal_modified=False,effects_modified=False,ownership_modified=False)
    (RELEASE/'gear-audit.json').write_text(json.dumps(audit,indent=2)+'\n')
    print(json.dumps({k:v for k,v in audit.items() if not k.endswith('_families')}))

if __name__=='__main__':main()
