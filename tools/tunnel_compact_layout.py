def placements():
    result={}
    for _,classes,(cx,cy) in CLASS_AREAS:
        for cls,offsets in zip(classes,PAIR_OFFSETS):
            for ident,(dx,dy) in zip(class_members()[cls],offsets):result[ident]=pos(cx+dx,cy+dy,cx,cy)
    for group in (SUPPLIES,SERVICES):result.update({i:pos(*p) for i,p in group.items()})
    for _,ids,points,center in TRADER_GROUPS:
        for ident,(x,y) in zip(ids,points):result[ident]=pos(x,y,*(center or (x,y+12)))
    return result

def paths():
    return {ident:[dict(pos(*p,*points[j+1 if j+1<len(points) else j-1]),pause=11+(ident*7+j*13)%38)
                   for j,p in enumerate(points)] for ident,points in WALKERS.items()}
