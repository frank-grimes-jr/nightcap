"""Generate the single vendor-restock entry point for legacy and arrival hubs."""
import argparse
import json
from pathlib import Path

from pok_hub import build_plan
from pok_hub_migration import desired, insert, sql_value


def generate(before, audit, legacy):
    plan = build_plan(audit)
    after = desired(before,audit)
    stock = [r for r in after['rows']['merchantlist'] if 99300 <= int(r['merchantid']) <= 99315]
    levels = {(str(m['merchant_id']),str(i['item_id'])):i['class_level'] for m in plan['merchants'] for i in m['items']}
    era = next(r['rule_value'] for r in before['rows']['rule_values'] if r['rule_name']=='Expansion:CurrentExpansion')
    identities = ' OR '.join(f"(id={m['npc_id']} AND BINARY name=BINARY {sql_value(m['name'])} AND merchant_id={m['merchant_id']} AND class=41)" for m in plan['merchants'])
    seeds = '\n'.join(insert('nightcap_pok_desired_stock',dict(r,hub_class_level=str(levels[(r['merchantid'],r['item'])]))) for r in stock)
    columns = before['schemas']['merchantlist']['columns']
    select = ','.join('ROW_NUMBER() OVER (PARTITION BY merchantid ORDER BY slot)' if c=='slot' else f'`{c}`' for c in columns)
    # Keep the existing archetype behavior until the arrival-hub migration is
    # applied. Inline the former split procedure so all restocking is one unit.
    legacy_body = legacy[legacy.index('-- Caster: Necromancer'):legacy.index('DROP PROCEDURE IF EXISTS split_vendor;')]
    for base, overflow in [(99221,99251),(99222,99252),(99224,99253)]:
        legacy_body += f"""
SELECT COUNT(*) INTO n FROM merchantlist WHERE merchantid={base};
DELETE FROM merchantlist WHERE merchantid={overflow};
IF n > 480 THEN
SET half_count=CEIL(n/2);
INSERT INTO merchantlist (merchantid,slot,item)
 SELECT {overflow},ROW_NUMBER() OVER (ORDER BY slot),item FROM merchantlist WHERE merchantid={base} AND slot>half_count;
DELETE FROM merchantlist WHERE merchantid={base} AND slot>half_count;
END IF;
"""
    return f"""-- GENERATED by tools/pok_hub_restock.py; canonical entry point for apply-era and operators.
-- Arrival-hub stock uses audited ORIGINAL class levels, never widened spells_new classes.
-- Preserves current item availability, merchant restrictions, and item prices.
-- Approved inventory: expansion {era}, level cap 1..50. Review a new catalog before later releases.
-- Legacy archetype behavior is retained only while no arrival-hub NPCs/stock exist.
-- Run with mysql without --force. A failure rolls back the entire restock.
DELIMITER //
BEGIN NOT ATOMIC
DECLARE n BIGINT;
DECLARE hub_count INT;
DECLARE cap_text VARCHAR(100);
DECLARE half_count INT;
DECLARE held INT DEFAULT 0;
DECLARE EXIT HANDLER FOR SQLEXCEPTION
BEGIN
ROLLBACK;
DROP TEMPORARY TABLE IF EXISTS nightcap_pok_desired_stock;
IF held=1 THEN DO RELEASE_LOCK('nightcap_pok_hub'); END IF;
RESIGNAL;
END;
SELECT GET_LOCK('nightcap_pok_hub',0) INTO held;
IF held<>1 OR held IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='PoK content operation already running'; END IF;
SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;
START TRANSACTION;
SELECT COUNT(*) INTO n FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='merchantlist' AND ENGINE='InnoDB';
IF n<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Merchant restock requires InnoDB'; END IF;
SELECT COUNT(*) INTO n FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE() AND EVENT_OBJECT_TABLE='merchantlist';
IF n<>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Review merchantlist triggers before restocking'; END IF;
SET cap_text=(SELECT rule_value FROM rule_values WHERE rule_name='Character:MaxLevel' AND ruleset_id=1);
IF cap_text IS NULL OR cap_text NOT REGEXP '^[0-9]+$' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Missing or invalid level cap'; END IF;
SET @cap=CAST(cap_text AS UNSIGNED);
IF @cap IS NULL OR @cap NOT BETWEEN 1 AND 255 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Missing or invalid level cap'; END IF;
SELECT COUNT(*) INTO hub_count FROM npc_types WHERE id BETWEEN 997900 AND 997915 OR merchant_id BETWEEN 99300 AND 99315 FOR UPDATE;
IF hub_count=0 THEN
SELECT COUNT(*) INTO n FROM merchantlist WHERE merchantid BETWEEN 99300 AND 99315 FOR UPDATE;
IF n<>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Arrival stock exists without hub NPCs'; END IF;
{legacy_body}
ELSE
IF hub_count<>16 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Incomplete or conflicting arrival hub'; END IF;
SELECT COUNT(*) INTO n FROM npc_types WHERE {identities};
IF n<>16 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Arrival merchant identities changed'; END IF;
IF @cap>50 OR (SELECT rule_value FROM rule_values WHERE ruleset_id=1 AND rule_name='Expansion:CurrentExpansion') <> {sql_value(era)}
 OR (SELECT COUNT(*) FROM rule_values WHERE ruleset_id=1 AND rule_name='Expansion:CurrentExpansion') <> 1
THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Review arrival-hub catalog for the requested era before restocking'; END IF;
CREATE TEMPORARY TABLE nightcap_pok_desired_stock AS SELECT merchantlist.*,CAST(0 AS UNSIGNED) AS hub_class_level FROM merchantlist WHERE 0;
{seeds}
SELECT COUNT(*) INTO n FROM nightcap_pok_desired_stock stock JOIN items i ON i.id=stock.item WHERE i.itemtype=20;
IF n<>{len(stock)} THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Arrival scroll items missing or changed type'; END IF;
""" + '\n'.join(
        f"IF (SELECT COUNT(*) FROM items WHERE id={i['item_id']} AND scrolleffect={i['spell_id']} AND BINARY Name=BINARY {sql_value(i['item_name'])})<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Arrival scroll identity drift'; END IF;"
        for i in audit['stock']) + f"""
SELECT COUNT(*) INTO n FROM (SELECT merchantid FROM nightcap_pok_desired_stock WHERE hub_class_level<=@cap GROUP BY merchantid HAVING COUNT(*)>500) oversized;
IF n<>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Arrival stock exceeds RoF2 merchant capacity'; END IF;
DELETE FROM merchantlist WHERE merchantid BETWEEN 99300 AND 99315;
INSERT INTO merchantlist ({','.join('`'+c+'`' for c in columns)})
SELECT {select} FROM nightcap_pok_desired_stock WHERE hub_class_level<=@cap;
DROP TEMPORARY TABLE nightcap_pok_desired_stock;
END IF;
COMMIT;
DO RELEASE_LOCK('nightcap_pok_hub');
END //
DELIMITER ;
SELECT merchantid,COUNT(*) AS stocked FROM merchantlist
WHERE merchantid IN (99221,99222,99223,99224,99251,99252,99253) OR merchantid BETWEEN 99300 AND 99315 GROUP BY merchantid;
"""


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--snapshot',type=Path,required=True)
    parser.add_argument('--audit',type=Path,required=True)
    parser.add_argument('--legacy',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    result=generate(json.loads(args.snapshot.read_bytes()),json.loads(args.audit.read_bytes()),args.legacy.read_text(encoding='utf-8'))
    args.output.write_bytes(result.encode())


if __name__=='__main__':
    main()
