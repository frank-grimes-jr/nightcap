def placements():
    result={}
    for _,classes,center,points in CLASS_GROUPS:
        for ident,p in zip([i for c in classes for i in class_members()[c]],points):
            result[ident]=pos(*p,*center)
    result.update({i:pos(*p,*RING_CENTER) for i,p in RING.items()})
    for group in (SUPPLIES,TRADERS,SERVICES):
        result.update({i:pos(*p) for i,p in group.items()})
    return result

def paths():
    result={}
    for ident,points in WALKERS.items():
        # GridPatrol reverses at the ends. Face into the aisle at each distinct
        # pause; randomized native pause mode breaks synchronized marching.
        result[ident]=[dict(pos(*p,*points[j+1 if j+1<len(points) else j-1]),
                            pause=11+(ident*7+j*13)%38)
                       for j,p in enumerate(points)]
    return result
