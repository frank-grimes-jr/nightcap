"""Generate guarded SQL for per-zone Hunt drop chances from config/zone-hunt-rates.json."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
FIELDS=('augment_chance','gear_chance')

def zones(catalog):
    return {z['short_name']:z['zoneidnumber'] for z in catalog['zones'] if z['status'] in ('Hunt draft','Access check')}

def rates(config,known):
    unknown=set(config['zones'])-set(known)
    if unknown: raise ValueError(f'Unknown hunt zones: {sorted(unknown)}')
    result={}
    for name in known:
        r={**config['default'],**config['zones'].get(name,{})}
        if set(r)!=set(FIELDS) or not all(type(v) is int and 0<=v<=10000 for v in r.values()):
            raise ValueError(f'Invalid rates for {name}: {r}')
        result[name]=r
    return result

def sql(config,known):
    r=rates(config,known)
    # Columns first: the old binary ignores them; the new binary disables hunt drops without them.
    out=['-- Generated by tools/zone_hunt_rates.py; reload all zones afterwards (rates load at zone boot).',
         'ALTER TABLE nightcap_zone_hunt_zones '+', '.join(
             f'ADD COLUMN IF NOT EXISTS {f} SMALLINT NOT NULL DEFAULT 50 CHECK ({f} BETWEEN 0 AND 10000)' for f in FIELDS)+';',
         'DELIMITER //','BEGIN NOT ATOMIC',' DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;',' START TRANSACTION;',
         f' IF (SELECT COUNT(*) FROM nightcap_zone_hunt_zones WHERE zone_id IN ({",".join(str(known[n]) for n in sorted(r))}))<>{len(r)} THEN'
         " SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Hunt zone rows missing'; END IF;"]
    for name in sorted(r):
        out.append(f" UPDATE nightcap_zone_hunt_zones SET {', '.join(f'{f}={r[name][f]}' for f in FIELDS)} WHERE zone_id={known[name]};")
    out+=[' COMMIT;','END//','DELIMITER ;']
    return '\n'.join(out)+'\n'

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    catalog=json.loads((ROOT/'docs/releases/zone-loot-20261009/approved-catalog.json').read_text(encoding='utf-8'))
    config=json.loads((ROOT/'config/zone-hunt-rates.json').read_text(encoding='utf-8'))
    a.output.write_text(sql(config,zones(catalog)),encoding='utf-8',newline='\n')
