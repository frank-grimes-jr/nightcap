"""Bind the mandatory proxy and packager to one generated classic asset set."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--assets', required=True, type=Path)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
raw = (ROOT/'eq-client-dll/config/classic-models.json').read_bytes()
plan = json.loads(raw)
audit = json.loads((args.assets/'classic-audit.json').read_bytes())
assert audit['plan_sha256'] == hashlib.sha256(raw).hexdigest(), 'assets belong to another model plan'
names = sorted([a['output'] for a in plan['archives']] +
               [a['archive'] for a in plan['global_models']] +
               ['nightcap_models_chr.txt', 'nightcap_modern_chr.txt'])
assert sorted(audit['files']) == names
lines = ['// Generated by tools/generate-classic-model-contract.py; do not edit.',
         '#pragma once', 'namespace nightcap { namespace models {',
         'struct Registration { int race; int gender; const char* original; const char* alias; const char* skeleton; };',
         'static const Registration kRegistrations[] = {']
for item in plan['registrations']:
    sources = [source for archive in plan['archives'] for source, alias in archive['aliases'].items() if alias == item['alias']]
    assert len(sources) == 1, 'ambiguous skeleton alias'
    assert len(sources[0]) == len(item['alias']) == 3 and sources[0].isalnum() and item['alias'].isalpha(), 'invalid skeleton code'
    lines.append('    {%d,%d,"%s","%s","%s"},' % (item['race'],item['gender'],item['original'],item['alias'],sources[0]))
lines += ['};', 'struct Remake { int race; int original; int gender; };', 'static const Remake kRemakes[] = {']
for race, original in plan['remakes'].items():
    gender = plan.get('remake_genders', {}).get(race, -1)
    assert gender in (-1,0,1,2), 'invalid original gender'
    lines.append('    {%s,%d,%d},' % (race,original,gender))
lines += ['};', 'struct Asset { const wchar_t* name; unsigned long size; unsigned char sha256[32]; };',
          'static const Asset kAssets[] = {']
for name in names:
    data = (args.assets/name).read_bytes()
    entry = audit['files'][name]
    assert entry == {'size':len(data),'sha256':hashlib.sha256(data).hexdigest()}
    sha = ','.join('0x'+entry['sha256'][i:i+2] for i in range(0,64,2))
    lines.append('    {L"%s",%d,{%s}},' % (name,len(data),sha))
lines += ['};','}}','']
outputs = {ROOT/'eq-client-dll/src/model_catalog.h':'\n'.join(lines),
           ROOT/'eq-launcher/cmd/nightcap-package/classic_models.go':
           '// Code generated by generate-classic-model-contract.py; DO NOT EDIT.\npackage main\n\nvar classicModelNames = []string{\n'+
           ''.join('\t"'+name+'",\n' for name in names)+'}\n\nvar classicModelDigests = map[string]string{\n'+
           ''.join('\t'+('"'+name+'":').ljust(max(map(len,names))+4)+'"'+audit['files'][name]['sha256']+'",\n' for name in names)+'}\n'}
for path, content in outputs.items():
    if args.check:
        assert path.read_text() == content, str(path)+' needs regeneration'
    else:
        path.write_bytes(content.encode('utf-8'))
print('Bound %d classic assets, %d registrations and %d remakes' % (len(names),len(plan['registrations']),len(plan['remakes'])))
